create policy meal_plan_items_owner_all on public.meal_plan_items
  for all to authenticated
  using (
    exists (
      select 1
      from public.meal_plans p
      where p.id = meal_plan_id and p.user_id = (select auth.uid())
    )
    and (
      recipe_id is null
      or exists (
        select 1
        from public.recipes r
        where r.id = recipe_id and r.user_id = (select auth.uid())
      )
    )
  )
  with check (
    exists (
      select 1
      from public.meal_plans p
      where p.id = meal_plan_id and p.user_id = (select auth.uid())
    )
    and (
      recipe_id is null
      or exists (
        select 1
        from public.recipes r
        where r.id = recipe_id and r.user_id = (select auth.uid())
      )
    )
  );

